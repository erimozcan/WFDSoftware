def load_airfoil_set(ui):
    validate_airfoil_transition_ranges()

    paths = {
        'root': RootAirfoilPath,
        'mid': MidAirfoilPath,
        'tip': TipAirfoilPath
    }
    labels = {
        'root': 'root/thick',
        'mid': 'mid-span',
        'tip': 'tip/thin'
    }

    for key in ('root', 'mid', 'tip'):
        if not paths[key]:
            path = select_airfoil_dat(ui, labels[key])
